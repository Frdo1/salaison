export const DICTS: Record<Lang, Dict> = { fr, en, es, it, de, pt };

export type TKey = keyof Dict;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s: string = DICTS[lang][key] ?? fr[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Nombre au format de la langue (virgule décimale sauf en anglais). */
export function fmtNum(lang: Lang, n: number, digits = 1) {
  const s = (Math.round(n * 10 ** digits) / 10 ** digits).toString();
  return lang === 'en' ? s : s.replace('.', ',');
}

export function fmtDate(d: Date) {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${p(d.getDate())}/${p(d.getMonth() + 1)}/${d.getFullYear()}`;
}

export type I18n = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  n: (n: number, digits?: number) => string;
};

export const I18nContext = createContext<I18n>({
  lang: 'fr',
  setLang: () => {},
  t: (k, v) => translate('fr', k, v),
  n: (x, d) => fmtNum('fr', x, d),
});

export const useI18n = () => useContext(I18nContext);
